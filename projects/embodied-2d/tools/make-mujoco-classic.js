// Turns the official @mujoco/mujoco ES module + .wasm into one classic script with the wasm embedded (base64),
// so it loads from file:// and can be handed to Web Workers as source, like vendor/rapier2d.js.
// usage: node projects/embodied-2d/tools/make-mujoco-classic.js <unpacked @mujoco/mujoco package dir> projects/embodied-2d/vendor/mujoco.js
const fs = require('fs'), path = require('path');
const [pkg, out] = process.argv.slice(2);
let src = fs.readFileSync(path.join(pkg, 'mujoco.js'), 'utf8');
const metaCount = (src.match(/import\.meta\.url/g) || []).length;
if (metaCount !== 4 || !/export default loadMujoco;\s*$/.test(src)) throw new Error('unexpected mujoco.js layout: ' + metaCount);
src = src.replace(/import\.meta\.url/g, '__mjBase').replace(/export default loadMujoco;\s*$/, 'return loadMujoco;');
const b64 = fs.readFileSync(path.join(pkg, 'mujoco.wasm')).toString('base64');
const version = JSON.parse(fs.readFileSync(path.join(pkg, 'package.json'), 'utf8')).version;
fs.writeFileSync(out, `/* MuJoCo ${version} (Apache-2.0, Google DeepMind), official JS bindings bundled as a plain script with the
   WebAssembly embedded, so it works from file:// and can be passed to training workers as source.
   loadMujocoClassic() -> Promise<mujoco>. Generated by tools/make-mujoco-classic.js; don't edit by hand. */
function __mujocoFactory() {
var __mjBase = typeof location !== 'undefined' && /^(https?|file):/.test(location.href) ? location.href : 'file:///mujoco.js';   // workers run from a blob: URL
${src}
}
var __MUJOCO_WASM_B64 = "${b64}";
function loadMujocoClassic() {
  var s = atob(__MUJOCO_WASM_B64), bin = new Uint8Array(s.length);
  for (var i = 0; i < s.length; i++) bin[i] = s.charCodeAt(i);
  return __mujocoFactory()({ wasmBinary: bin });
}
`);
console.log('wrote', out, (fs.statSync(out).size / 1e6).toFixed(1), 'MB');
